export function getMoviesByMood(mood) {
  return movies.filter((m) => m.moods.includes(mood));
}

export function getMovieById(id) {
  return movies.find((m) => m.id === id) || null;
}

export function pickRandom(list) {
  if (!list.length) return null;
  return list[Math.floor(Math.random() * list.length)];
}

export function getRetailer(id) {
  return RETAILERS.find((r) => r.id === id) || null;
}

export function getMoviesByRetailer(id) {
  return movies.filter((m) => m.retailers.includes(id));
}

export function normalizeGenre(genre) {
  if (genre === 'Animation') return 'Animated';
  if (genre === 'History') return 'Historical';
  return genre;
}

export function movieHasGenre(movie, genre) {
  if (!genre) return true;
  const aliases = GENRE_ALIASES[genre] || [genre];
  return movie.genres.some((g) => aliases.includes(g) || normalizeGenre(g) === genre);
}

export function assertCatalog() {
  const main = GENRE_PILLS;
  const genreCounts = Object.fromEntries(main.map((g) => [g, 0]));
  const subCounts = {};
  for (const vals of Object.values(SUBGENRES)) {
    for (const s of vals) subCounts[s] = 0;
  }
  const global = [];
  const byGenre = Object.fromEntries(main.map((g) => [g, []]));
  const arrivals = [];
  const ids = new Set();

  for (const movie of movies) {
    if (ids.has(movie.id)) console.error('duplicate id', movie.id);
    ids.add(movie.id);
    const hit = new Set();
    for (const g of movie.genres) hit.add(normalizeGenre(g));
    for (const g of main) {
      if (movieHasGenre(movie, g) || hit.has(g)) genreCounts[g] += 1;
    }
    for (const s of movie.subgenres || []) {
      if (s in subCounts) subCounts[s] += 1;
    }
    if (movie.top10) global.push({ rank: movie.top10, title: movie.title, id: movie.id });
    for (const [g, n] of Object.entries(movie.top10ByGenre || {})) {
      if (byGenre[g]) byGenre[g].push({ rank: n, title: movie.title, id: movie.id });
    }
    if (movie.newArrivalRank) arrivals.push({ rank: movie.newArrivalRank, title: movie.title, id: movie.id });
  }

  const uniqRanks = (rows) => {
    const ranks = rows.map((r) => r.rank).sort((a, b) => a - b);
    return ranks.length === 10 && ranks.every((n, i) => n === i + 1);
  };

  console.log('films', movies.length);
  console.log('genre counts', genreCounts);
  console.log('subgenre counts', subCounts);
  console.log('global top10', global.sort((a, b) => a.rank - b.rank));
  for (const g of main) {
    console.log('top10', g, byGenre[g].sort((a, b) => a.rank - b.rank));
  }
  console.log('new arrivals', arrivals.sort((a, b) => a.rank - b.rank));

  const problems = [];
  for (const g of main) {
    if (genreCounts[g] < 20) problems.push(`${g} has ${genreCounts[g]} (<20)`);
    if (!uniqRanks(byGenre[g])) problems.push(`${g} top10 ranks invalid (${byGenre[g].length})`);
  }
  if (!uniqRanks(global)) problems.push('global top10 ranks invalid');
  if (!uniqRanks(arrivals)) problems.push('new arrivals ranks invalid');
  for (const [s, n] of Object.entries(subCounts)) {
    if (n < 1) problems.push(`subgenre uncovered: ${s}`);
  }
  if (problems.length) {
    console.error('CATALOG FAIL');
    for (const p of problems) console.error(' -', p);
    throw new Error('assertCatalog failed');
  }
  console.log('CATALOG OK');
}

