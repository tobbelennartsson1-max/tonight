// Builds the browser extension's shared files from the web app sources and zips it.
//   - extension/shared/i18n.js   ← src/i18n/locales/*.js (together.*, ext.* strings, all 7 languages)
//   - extension/shared/effects.js ← src/lib/effects.js (same reactions/confetti code as the web app)
//   - /workspace/tonight-extension.zip (override with EXT_ZIP=…)
import fs from 'node:fs';
import path from 'node:path';
import zlib from 'node:zlib';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const ext = path.join(root, 'extension');
const out = process.env.EXT_ZIP || path.resolve(root, '..', 'tonight-extension.zip');

const { LANGUAGES } = await import(pathToFileURL(path.join(root, 'src/i18n/languages.js')));
const dicts = {};
for (const l of LANGUAGES) {
  dicts[l.code] = Object.fromEntries(
    Object.entries(l.dict.ui).filter(([k]) => k.startsWith('together.') || k.startsWith('ext.') || k === 'lang.label'),
  );
}
const langs = LANGUAGES.map((l) => ({ code: l.code, label: l.label }));
fs.mkdirSync(path.join(ext, 'shared'), { recursive: true });
fs.writeFileSync(
  path.join(ext, 'shared/i18n.js'),
  `// Generated by scripts/build-extension.mjs — do not edit.
var TonightI18n = (() => {
  const dicts = ${JSON.stringify(dicts)};
  const langs = ${JSON.stringify(langs)};
  const has = (l) => !!l && Object.prototype.hasOwnProperty.call(dicts, l);
  const t = (lang, key, vars) => {
    const s = (dicts[lang] && dicts[lang][key]) || dicts.en[key] || key;
    return vars ? s.replace(/\\{(\\w+)\\}/g, (m, k) => (vars[k] != null ? String(vars[k]) : m)) : s;
  };
  return { dicts, langs, has, t };
})();
`,
);

const fxSrc = fs.readFileSync(path.join(root, 'src/lib/effects.js'), 'utf8').replace(/^export /gm, '');
fs.writeFileSync(
  path.join(ext, 'shared/effects.js'),
  `// Generated from src/lib/effects.js by scripts/build-extension.mjs — do not edit.
var TonightFx = (() => {
${fxSrc}
  return { createFx, REACTIONS, EFFECT_KINDS };
})();
`,
);

// Minimal zip writer (deflate), no dependencies.
function walk(dir, base = '') {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((d) => {
    const rel = path.posix.join(base, d.name);
    if (d.name.startsWith('.')) return [];
    return d.isDirectory() ? walk(path.join(dir, d.name), rel) : [rel];
  });
}
const files = walk(ext).sort();
const locals = [];
const central = [];
let offset = 0;
for (const rel of files) {
  const data = fs.readFileSync(path.join(ext, rel));
  const comp = zlib.deflateRawSync(data, { level: 9 });
  const crc = zlib.crc32(data);
  const name = Buffer.from(rel);
  const lh = Buffer.alloc(30);
  lh.writeUInt32LE(0x04034b50, 0);
  lh.writeUInt16LE(20, 4);
  lh.writeUInt16LE(0x0800, 6);
  lh.writeUInt16LE(8, 8);
  lh.writeUInt32LE(0x00210000, 10);
  lh.writeUInt32LE(crc, 14);
  lh.writeUInt32LE(comp.length, 18);
  lh.writeUInt32LE(data.length, 22);
  lh.writeUInt16LE(name.length, 26);
  locals.push(lh, name, comp);
  const ch = Buffer.alloc(46);
  ch.writeUInt32LE(0x02014b50, 0);
  ch.writeUInt16LE(20, 4);
  ch.writeUInt16LE(20, 6);
  ch.writeUInt16LE(0x0800, 8);
  ch.writeUInt16LE(8, 10);
  ch.writeUInt32LE(0x00210000, 12);
  ch.writeUInt32LE(crc, 16);
  ch.writeUInt32LE(comp.length, 20);
  ch.writeUInt32LE(data.length, 24);
  ch.writeUInt16LE(name.length, 28);
  ch.writeUInt32LE(offset, 42);
  central.push(ch, name);
  offset += 30 + name.length + comp.length;
}
const cdSize = central.reduce((a, b) => a + b.length, 0);
const end = Buffer.alloc(22);
end.writeUInt32LE(0x06054b50, 0);
end.writeUInt16LE(files.length, 8);
end.writeUInt16LE(files.length, 10);
end.writeUInt32LE(cdSize, 12);
end.writeUInt32LE(offset, 16);
fs.writeFileSync(out, Buffer.concat([...locals, ...central, end]));
console.log(`extension: ${files.length} files → ${out}`);
